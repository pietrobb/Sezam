"""Write docs/AUTHORITY_MAP.md from server/app/authority.py and src/sezam/authority.py.

    python scripts/authority_map.py          # rewrite the document
    python scripts/authority_map.py --check  # exit 1 when it is stale

tests/test_authority_map.py fails while the document differs from the maps.
"""

from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
for path in (ROOT, ROOT / "src"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

from server.app import authority as server  # noqa: E402
from sezam import authority as client  # noqa: E402

DOC = ROOT / "docs" / "AUTHORITY_MAP.md"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ") or "—"


def _list(items) -> str:
    return "<br>".join(f"`{i}`" for i in items) or "—"


def _tests(items) -> str:
    return "<br>".join(i.removeprefix("tests/") for i in items) or "—"


def _client_table(title: str, ops: dict, intro: str) -> list[str]:
    lines = [f"## {title}", "", intro, "",
             "| Operation | Changes | Who may | Decided by | Tests / run by |", "|---|---|---|---|---|"]
    for key in sorted(ops):
        op = ops[key]
        covered = _tests(op.tests)
        if op.part_of:
            covered = (covered + "<br>" if op.tests else "") + "run by " + _list(op.part_of)
        if op.via:
            covered = (covered + "<br>" if op.tests else "") + "runs " + _list(op.via)
        note = f" ({_cell(op.note)})" if op.note else ""
        lines.append(f"| `{key}` | {_cell(op.changes)}{note} | {_cell(op.who) if op.changes else '—'} "
                     f"| {_list(op.decided_by)} | {covered} |")
    return lines + [""]


def render() -> str:
    writes = sum(1 for r in server.ROUTES.values() if r.changes)
    lines = [
        "# Authority map",
        "",
        "Generated by `python scripts/authority_map.py` from `server/app/authority.py` and",
        "`src/sezam/authority.py` (docs/ROOT_CAUSE_PLAN.md S1, INV-2). Do not edit by hand:",
        "`tests/test_authority_map.py` fails while this file differs from the maps, when a",
        "route, CLI command, MCP tool or client operation has no entry, when a route mapped",
        "as reading writes SQL, and when a named check, caller or test does not match the code.",
        "",
        "The rules these checks apply (team log replay and authority, key vouchers, signed",
        "messages, formats, sync and team log orchestration) are sezam-sync-core's (`core/`,",
        "INV-9, S3, docs/CORE_UNIFICATION.md); the named checks gather inputs and act on its",
        "answer. `tests/test_core_ratchet.py` fails when a core rule is written again outside",
        "a thin wrapper on the desktop, the server, the page or the phone.",
        "",
        f"Server: {len(server.ROUTES)} routes, {writes} of them change something.",
        "",
        "## Server routes",
        "",
        "| Route | Changes | Who may | Checked by | Tests |",
        "|---|---|---|---|---|",
    ]
    for key, route in server.ROUTES.items():
        note = f" ({_cell(route.note)})" if route.note else ""
        lines.append(f"| `{key}` | {_cell(route.changes)}{note} | {_cell(route.who)} "
                     f"| {_list(route.checks)} | {_tests(route.tests)} |")
    lines.append("")
    lines += _client_table("CLI commands", client.CLI, "`sezam <command>`; *runs* names the operations below.")
    lines += _client_table("MCP tools", client.MCP, "None of them changes the vault.")
    lines += _client_table("Vault (`sezam.vault.crud.Vault`)", client.VAULT,
                           "Local changes; the push sends them and the server decides there.")
    lines += _client_table("SyncClient (`sezam.vault.sync_client.SyncClient`)", client.SYNC,
                           "The client side of every route; the team log's records are checked against the log.")
    lines += _client_table("Functions of `sezam.vault` the CLI, GUI and MCP call", client.FUNCTIONS,
                           "Keyed `module:function` under `sezam.vault`.")
    lines += _client_table("Classes of `sezam.vault` the CLI, GUI and MCP use", client.CLASSES, "")
    lines += _client_table("CLI, GUI and MCP code that calls the server itself", client.DIRECT,
                           "Keyed `module:function` under `sezam`; every such function must be here.")
    lines += ["## Without a test", "",
              "Operations that change something and have no test yet (the list may only shrink):", ""]
    lines += [f"- `{key}`" for key in sorted(client.UNTESTED)] + [""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if DOC.read_text(encoding="utf-8") != text:
            print("docs/AUTHORITY_MAP.md is stale: python scripts/authority_map.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
