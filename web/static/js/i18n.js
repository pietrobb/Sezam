    function resolveLanguage(language) {
        return Object.prototype.hasOwnProperty.call(LANGUAGES, language)
            ? language
            : DEFAULT_LANGUAGE;
    }

    function translate(language, key, values = {}) {
        const resolved = resolveLanguage(language);
        const template = LANGUAGES[resolved][key] ?? LANGUAGES[DEFAULT_LANGUAGE][key] ?? key;
        return Object.entries(values).reduce(
            (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
            template,
        );
    }

    function listLanguages() {
        return Object.entries(LANGUAGES).map(([code, messages]) => ({
            code,
            name: messages['language.name'] || code,
        }));
    }

    function elementValues(element) {
        if (!element.dataset.i18nValues) return {};
        try {
            return JSON.parse(element.dataset.i18nValues);
        } catch {
            return {};
        }
    }

    function applyDocument(root, language) {
        const resolved = resolveLanguage(language);
        const translateElement = (element, key, property) => {
            const text = translate(resolved, key, elementValues(element));
            if (property === 'textContent') element.textContent = text;
            else if (property === 'innerHTML') element.innerHTML = text;
            else element.setAttribute(property, text);
        };
        root.querySelectorAll('[data-i18n]').forEach((element) =>
            translateElement(element, element.dataset.i18n, 'textContent'));
        root.querySelectorAll('[data-i18n-html]').forEach((element) =>
            translateElement(element, element.dataset.i18nHtml, 'innerHTML'));
        root.querySelectorAll('[data-i18n-placeholder]').forEach((element) =>
            translateElement(element, element.dataset.i18nPlaceholder, 'placeholder'));
        root.querySelectorAll('[data-i18n-title]').forEach((element) =>
            translateElement(element, element.dataset.i18nTitle, 'title'));
        root.querySelectorAll('[data-i18n-aria-label]').forEach((element) =>
            translateElement(element, element.dataset.i18nAriaLabel, 'aria-label'));
        if (root.documentElement) root.documentElement.lang = resolved;
        return resolved;
    }

    globalThis.SezamI18n = Object.freeze({
        defaultLanguage: DEFAULT_LANGUAGE,
        languages: LANGUAGES,
        applyDocument,
        listLanguages,
        resolveLanguage,
        translate,
    });
