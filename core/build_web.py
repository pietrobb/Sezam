"""Build the web binding of sezam-sync-core (docs/SYNC_SINGLE_SOURCE.md 4b).

Writes web/static/js/vendor/sezam-sync-core.js: the wasm-bindgen glue with
the module inlined, exposing ``SezamSyncCore.ready`` (a promise) and
``SezamSyncCore.call(op, args)``. The page loads it as a plain script, as it
loads libsodium. The file names the digest of the core sources it was built
from; tests/test_sync_core_web.py refuses a file older than the sources, so
run this after every change under core/ (Docker needed):

    python core/build_web.py

Reproducible (review c78fd19): CI builds it again from source and refuses a
committed file that differs byte for byte. The build runs in the official
image of the compiler core/rust-toolchain.toml pins, with the wasm-bindgen
core/wasm/Cargo.toml pins, at fixed paths: the checkout's own path changed
the crates' hashes and so the module (two clones built two modules).
"""

import base64
import hashlib
import os
import re
import subprocess
import sys
from pathlib import Path

CORE = Path(__file__).resolve().parent
ROOT = CORE.parent
OUT = ROOT / "web" / "static" / "js" / "vendor" / "sezam-sync-core.js"
DIGEST_MARK = "// source-sha256: "


def source_files() -> list[Path]:
    files = [CORE / "rust-toolchain.toml", CORE / "Cargo.toml", CORE / "Cargo.lock",
             CORE / "wasm" / "Cargo.toml", CORE / "wasm" / "Cargo.lock"]
    files += sorted((CORE / "src").glob("*.rs")) + sorted((CORE / "wasm" / "src").glob("*.rs"))
    return files


def source_digest() -> str:
    """The same on every checkout (line endings normalised)."""
    digest = hashlib.sha256()
    for path in source_files():
        digest.update(path.relative_to(ROOT).as_posix().encode() + b"\0")
        digest.update(path.read_bytes().replace(b"\r\n", b"\n") + b"\0")
    return digest.hexdigest()


def built_digest() -> str | None:
    if not OUT.exists():
        return None
    for line in OUT.read_text(encoding="utf-8").splitlines()[:5]:
        if line.startswith(DIGEST_MARK):
            return line[len(DIGEST_MARK):].strip()
    return None


def remapped_env() -> dict[str, str]:
    """Panic locations would carry the builder's absolute paths (user name
    included, review c78fd19) into the public module; map them to neutral
    prefixes. The encoded form keeps a path with spaces whole; it replaces,
    not extends, any configured flags."""
    home = Path.home()
    cargo_home = Path(os.environ.get("CARGO_HOME") or home / ".cargo")
    rustup_home = Path(os.environ.get("RUSTUP_HOME") or home / ".rustup")
    # rustc applies the last matching prefix: the widest one comes first.
    prefixes = [(home, "/home"), (ROOT, "/sezam"), (rustup_home, "/rustup"), (cargo_home, "/cargo")]
    flags = "\x1f".join(f"--remap-path-prefix={src}={dst}" for src, dst in prefixes)
    env = {k: v for k, v in os.environ.items() if k != "RUSTFLAGS"}
    return {**env, "CARGO_ENCODED_RUSTFLAGS": flags}


def pinned(path: Path, pattern: str) -> str:
    return re.search(pattern, path.read_text(encoding="utf-8"), re.M).group(1)


def in_container() -> None:
    """Run this script again (`--here`) in the pinned toolchain's image."""
    rust = pinned(CORE / "rust-toolchain.toml", r'^channel = "([^"]+)"')
    bindgen = pinned(CORE / "wasm" / "Cargo.toml", r'^wasm-bindgen = "=([^"]+)"')
    subprocess.run(
        ["docker", "run", "--rm", "-v", f"{ROOT}:/src", "-w", "/src/core",
         "-e", "CARGO_TARGET_DIR=/tmp/target", f"rust:{rust}", "sh", "-c",
         f"cargo install -q wasm-bindgen-cli --locked --version {bindgen} && python3 build_web.py --here"],
        check=True,
    )


def main() -> None:
    wasm_crate = CORE / "wasm"
    subprocess.run(
        ["cargo", "build", "--release", "--target", "wasm32-unknown-unknown"],
        cwd=wasm_crate, check=True, env=remapped_env(),
    )
    target = Path(os.environ.get("CARGO_TARGET_DIR") or wasm_crate / "target")
    subprocess.run(
        ["wasm-bindgen", "--target", "no-modules", "--no-typescript", "--out-dir",
         str(target / "bindgen"), str(target / "wasm32-unknown-unknown" / "release" / "sezam_sync_core_wasm.wasm")],
        check=True,
    )
    glue = (target / "bindgen" / "sezam_sync_core_wasm.js").read_text(encoding="utf-8")
    # The module is inlined: no URL is derived from the script tag (in node
    # the tests' document has no currentScript).
    glue, found = re.subn(
        r"let script_src;\n\s*if \(typeof document !== 'undefined'.*?\n\s*}\n",
        "let script_src;\n", glue, count=1, flags=re.S,
    )
    if not found:
        sys.exit("wasm-bindgen glue changed: the script_src block was not found")
    wasm = base64.b64encode((target / "bindgen" / "sezam_sync_core_wasm_bg.wasm").read_bytes()).decode()
    OUT.write_text(
        "// Generated by core/build_web.py from sezam-sync-core (core/); do not edit.\n"
        f"{DIGEST_MARK}{source_digest()}\n"
        "var SezamSyncCore = (function () {\n"
        f"{glue}\n"
        f"const WASM = '{wasm}';\n"
        "const bytes = Uint8Array.from(atob(WASM), c => c.charCodeAt(0));\n"
        "let loaded = false;\n"
        "const ready = wasm_bindgen({ module_or_path: bytes }).then(() => { loaded = true; });\n"
        "function call(op, args) {\n"
        "    if (!loaded) throw new Error('sync core is not loaded yet');\n"
        "    const out = JSON.parse(wasm_bindgen.call(op, JSON.stringify(args)));\n"
        "    if (out.error !== undefined) throw new Error(`sync core ${op}: ${out.error}`);\n"
        "    return out.ok;\n"
        "}\n"
        "return { ready, call };\n"
        "})();\n",
        encoding="utf-8", newline="\n",
    )
    # The page pins it like the other vendored scripts (Subresource Integrity).
    index = ROOT / "web" / "templates" / "index.html"
    html, found = re.subn(
        r'(src="/static/js/vendor/sezam-sync-core\.js"\s+integrity=")[^"]*"',
        lambda m: f'{m.group(1)}{integrity()}"', index.read_bytes().decode("utf-8"),
    )
    if not found:
        sys.exit(f"{index.relative_to(ROOT)} does not load vendor/sezam-sync-core.js")
    index.write_bytes(html.encode("utf-8"))
    print(f"{OUT.relative_to(ROOT)}: {OUT.stat().st_size} bytes, {integrity()}")


def integrity() -> str:
    return "sha384-" + base64.b64encode(hashlib.sha384(OUT.read_bytes()).digest()).decode()


if __name__ == "__main__":
    main() if "--here" in sys.argv[1:] else in_container()
